"""Build independently encoded component streams and interleave complete temporal units."""
from hashlib import sha256
from pathlib import Path


AVM_REVISION = "a1ec4594d97028ebc34083ec8346616d697c2fc9"


def temporal_units(data):
    units = []
    pos = 0
    while pos < len(data):
        size = 0
        shift = 0
        while True:
            if pos >= len(data) or shift >= 56:
                raise ValueError("Invalid component OBU length prefix.")
            byte = data[pos]
            pos += 1
            size |= (byte & 127) << shift
            if byte < 128:
                break
            shift += 7
        if not size or pos + size > len(data):
            raise ValueError("Invalid OBU length in the component input.")
        obu = data[pos:pos + size]
        pos += size
        if obu == b"\x08":
            units.append([])
        elif units:
            units[-1].append(obu)
        else:
            raise ValueError("The first component OBU must be a temporal delimiter.")
    return units


def framed(obu):
    size = len(obu)
    result = bytearray()
    while size >= 128:
        result.append((size & 127) | 128)
        size >>= 7
    result.append(size)
    return result + obu


def layer_obu(obu, xlayer, bit_depth, layered):
    header_size = 2 if obu[0] & 128 else 1
    mlayer = obu[1] & 224 if header_size == 2 else 0
    header = bytes((obu[0] | 128, mlayer | xlayer))
    payload = bytearray(obu[header_size:])
    kind = (obu[0] >> 2) & 31
    if kind == 1 and not layered:
        # These component headers use ID 0, profile 2, level 0 and 4:2:0.
        # In § 5.4.1 bit_depth_idc uses one bit for 10-bit or three for 8-bit.
        offset = 16 if bit_depth == 8 else 14
        prefix = int.from_bytes(payload[:3], "big")
        if prefix >> (24 - offset) != (0x880a if bit_depth == 8 else 0x2203):
            raise ValueError("Unexpected sequence header in the AVM component.")
        shift = 24 - offset - 3
        if (prefix >> shift) & 7:
            raise ValueError("The AVM component already references an LCR.")
        payload[:3] = (prefix | (1 << shift)).to_bytes(3, "big")
    if kind == 16 and layered:
        # The sparse component's local LCR retains ID 1 and references global LCR 1.
        if payload[0] != 0x04:
            raise ValueError("Unexpected local LCR in the sparse component.")
        payload[0] |= 0x20
    return framed(header + payload)


def mux(left, right, bit_depth, layered=False):
    if len(left) != len(right):
        raise ValueError("The two components need the same number of temporal units.")
    result = bytearray()
    for index, (low, high) in enumerate(zip(left, right)):
        result += framed(b"\x08")
        if index == 0 or (index == 2 and not layered):
            # § 5.8.1: global LCR 1, xlayer map 0x88, no optional payload.
            # Enable the DOH constraint for the sparse nonmonotonic component.
            result += framed(bytes.fromhex(
                "c01f2000002200020040" if layered else "c01f2000002200000040"
            ))
        for obu in low:
            result += layer_obu(obu, 3, bit_depth, layered)
        for obu in high:
            result += layer_obu(obu, 7, bit_depth, False)
    return result


def verify_components(path, original, components, bit_depth, sparse, decoder, run_checked):
    if path.read_bytes() != original.read_bytes():
        raise ValueError(f"Generated bytes differ from the committed fixture {path.name}.")

    def decode(source):
        output = path.parent / (source.stem + ".yuv")
        run_checked([decoder, "--all-layers", "--rawvideo", "--i420", "-o", str(output), str(source)])
        return output.read_bytes()

    left = b"".join(decode(source) for source in components[:-1])
    right = decode(components[-1])
    # The sparse component outputs two 64x64 pictures in each TU.
    def frame_size(width):
        return width * 64 * 3 // 2 * (1 if bit_depth == 8 else 2)

    left_sizes = [2 * frame_size(64)] * 4 if sparse else [frame_size(w) for w in (64, 64, 80, 80)]
    right_size = frame_size(96)
    expected = bytearray()
    pos = 0
    for tu, size in enumerate(left_sizes):
        expected.extend(left[pos:pos + size])
        pos += size
        expected.extend(right[tu * right_size:(tu + 1) * right_size])
    if pos != len(left) or len(right) != 4 * right_size or decode(path) != expected:
        raise ValueError(f"AVM multiplexed output differs from the components for {path.name}.")
    print(f"{path.name} input={sha256(path.read_bytes()).hexdigest()} "
          f"raw={sha256(expected).hexdigest()} x3={sha256(left).hexdigest()} x7={sha256(right).hexdigest()}")


def generate(valid, stage, encoder, decoder, write_y4m, run_checked):
    stage = Path(stage)
    for executable in (encoder, decoder):
        version = run_checked([executable, "--help"]).stdout.decode()
        if f"-g{AVM_REVISION[:10]}" not in version:
            raise ValueError(f"Build {Path(executable).name} from AVM revision {AVM_REVISION}.")
    if stage.exists() and any(stage.iterdir()):
        raise ValueError(f"Select an empty staging directory. {stage} contains files.")
    stage.mkdir(parents=True, exist_ok=True)
    valid = Path(valid)
    for depth in (8, 10):
        components = []
        for name, width, count, model, seed in (
            ("first", 64, 2, 1, 0),
            ("second", 80, 2, 2, 17),
            ("continuing", 96, 4, 3, 37),
        ):
            source = stage / f"{name}-{depth}.y4m"
            bitstream = source.with_suffix(".obu")

            def sample(t, x, y, plane, seed=seed, depth=depth):
                return (16 + ((3 * x + 5 * y + 13 * t + seed + 47 * plane) % 192)) << (depth - 8)

            write_y4m(source, width, 64, depth, sample, count)
            run_checked([
                encoder, str(source), "--obu", "--profile=2", "--i420", f"--bit-depth={depth}",
                f"--input-bit-depth={depth}", "--cpu-used=6", "--threads=1", "--qp=100",
                "--end-usage=q", "--lag-in-frames=0", "--passes=1", "--kf-min-dist=65",
                "--kf-max-dist=65", "--enable-keyframe-filtering=0", "--monotonic-output-order=1",
                f"--enable-mfh-obu-signaling={int(name == 'continuing')}",
                f"--film-grain-test={model}", f"--limit={count}", "--disable-warning-prompt",
                "--quiet", "-D", "-o", str(bitstream),
            ])
            components.append(bitstream)
        first, second, continuing = [temporal_units(source.read_bytes()) for source in components]
        path = stage / f"syn-xlayer-independent-reset-{depth}bit.obu"
        path.write_bytes(mux(first + second, continuing, depth))
        verify_components(path, valid / path.name, components, depth, False, decoder, run_checked)
        if depth == 8:
            sparse = valid / "syn-mlayer-tlayer-sparse-state.obu"
            path = stage / "syn-xlayer-independent-sparse-8bit.obu"
            path.write_bytes(mux(temporal_units(sparse.read_bytes()), continuing, depth, layered=True))
            verify_components(path, valid / path.name, [sparse, components[-1]], depth, True, decoder, run_checked)
